package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"

	"golang.org/x/mod/modfile"
	"golang.org/x/mod/module"
)

const modulePath = "github.com/goplus/builder/tools/ai"

type moduleDependency struct {
	Version            string
	ReplacementPath    string
	ReplacementVersion string
}

func main() {
	os.Exit(run(os.Args[1:], os.Stderr))
}

func run(args []string, stderr io.Writer) int {
	flags := flag.NewFlagSet("genversion", flag.ContinueOnError)
	flags.SetOutput(stderr)
	flags.Usage = func() {
		fmt.Fprintln(stderr, "usage: genversion -source <go.mod> -output <file>")
		flags.PrintDefaults()
	}
	sourcePath := flags.String("source", "", "path to the source go.mod file")
	outputPath := flags.String("output", "", "path to the generated Go file")
	if err := flags.Parse(args); err != nil {
		if err == flag.ErrHelp {
			return 0
		}
		return 2
	}
	if flags.NArg() != 0 {
		fmt.Fprintf(stderr, "unexpected arguments: %q\n", flags.Args())
		flags.Usage()
		return 2
	}

	if *sourcePath == "" || *outputPath == "" {
		flags.Usage()
		return 2
	}

	if err := generate(*sourcePath, *outputPath); err != nil {
		fmt.Fprintf(stderr, "generate builder ai version: %v\n", err)
		return 1
	}
	return 0
}

func generate(sourcePath, outputPath string) error {
	dependency, err := moduleDependencyFromFile(sourcePath)
	if err != nil {
		return err
	}
	content := fmt.Appendf(nil, `// Code generated by go generate; DO NOT EDIT.

package builderai

const Version = %q
const ReplacementPath = %q
const ReplacementVersion = %q
`, dependency.Version, dependency.ReplacementPath, dependency.ReplacementVersion)

	if existing, err := os.ReadFile(outputPath); err == nil && bytes.Equal(existing, content) {
		return nil
	} else if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read output %s: %w", outputPath, err)
	}

	if err := os.MkdirAll(filepath.Dir(outputPath), 0755); err != nil {
		return fmt.Errorf("create output dir for %s: %w", outputPath, err)
	}
	if err := os.WriteFile(outputPath, content, 0644); err != nil {
		return fmt.Errorf("write output %s: %w", outputPath, err)
	}
	return nil
}

func moduleDependencyFromFile(path string) (moduleDependency, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return moduleDependency{}, fmt.Errorf("read source %s: %w", path, err)
	}

	file, err := modfile.Parse(path, data, nil)
	if err != nil {
		return moduleDependency{}, fmt.Errorf("parse source %s: %w", path, err)
	}

	var dependency moduleDependency
	for _, req := range file.Require {
		if req.Mod.Path == modulePath {
			dependency.Version = req.Mod.Version
			break
		}
	}
	if dependency.Version == "" {
		return moduleDependency{}, fmt.Errorf("module %q not found in %s", modulePath, path)
	}

	var replacement *modfile.Replace
	for _, repl := range file.Replace {
		if repl.Old.Path != modulePath {
			continue
		}
		if repl.Old.Version == dependency.Version {
			replacement = repl
			break
		}
		if repl.Old.Version == "" {
			replacement = repl
		}
	}
	if replacement != nil {
		if replacement.New.Version == "" {
			return moduleDependency{}, fmt.Errorf("builder ai replacement must use a remote module with a version, got %q", replacement.New.Path)
		}
		if err := module.Check(replacement.New.Path, replacement.New.Version); err != nil {
			return moduleDependency{}, fmt.Errorf("invalid builder ai replacement: %w", err)
		}
		dependency.ReplacementPath = replacement.New.Path
		dependency.ReplacementVersion = replacement.New.Version
	}
	return dependency, nil
}
