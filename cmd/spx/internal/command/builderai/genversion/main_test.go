func TestModuleVersionFromFile(t *testing.T) {
	for _, tt := range []struct {
		name, content, want string
		missing             bool
	}{
		{name: "missing file", missing: true, want: "read source"},
		{name: "invalid module", content: "not a go.mod", want: "parse source"},
		{name: "missing requirement", content: "module example.com/demo\n", want: "not found"},
		{name: "matching requirement", content: "module example.com/demo\nrequire " + modulePath + " v1.2.3\n", want: "v1.2.3"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			source := filepath.Join(t.TempDir(), "go.mod")
			if !tt.missing {
				if err := os.WriteFile(source, []byte(tt.content), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			version, err := moduleVersionFromFile(source)
			if tt.name == "matching requirement" {
				if err != nil || version != tt.want {
					t.Fatalf("version=%q error=%v, want %q", version, err, tt.want)
				}
			} else if err == nil || !strings.Contains(err.Error(), tt.want) || version != "" {
				t.Fatalf("version=%q error=%v, want %q error", version, err, tt.want)
			}
		})
	}
}

func TestGenerateVersion(t *testing.T) {
	if encoded := os.Getenv("SPX_GENVERSION_TEST_ARGS"); encoded != "" {
		var args []string
		if err := json.Unmarshal([]byte(encoded), &args); err != nil {
			t.Fatal(err)
		}
		os.Args = append([]string{"genversion"}, args...)
		flag.CommandLine = flag.NewFlagSet("genversion", flag.ContinueOnError)
		main()
		return
	}
	source := filepath.Join(t.TempDir(), "go.mod")
	if err := os.WriteFile(source, []byte("module example.com/demo\nrequire "+modulePath+" v1.2.3\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Run("creates and reuses generated version", func(t *testing.T) {
		output := filepath.Join(t.TempDir(), "generated", "version_gen.go")
		args := []string{"-source", source, "-output", output}
		runGenerator(t, args, 0, "")
		data, err := os.ReadFile(output)
		want := "// Code generated by go generate; DO NOT EDIT.\n\npackage builderai\n\nconst Version = \"v1.2.3\"\n"
		if err != nil || string(data) != want {
			t.Fatalf("generated version=%q error=%v, want %q", data, err, want)
		}
		stamp := time.Unix(1_600_000_000, 0)
		if err := os.Chtimes(output, stamp, stamp); err != nil {
			t.Fatal(err)
		}
		before, err := os.Stat(output)
		if err != nil {
			t.Fatal(err)
		}
		runGenerator(t, args, 0, "")
		after, err := os.Stat(output)
		if err != nil {
			t.Fatal(err)
		}
		if !os.SameFile(before, after) || !after.ModTime().Equal(before.ModTime()) {
			t.Fatal("identical generated file was rewritten")
		}
	})
	t.Run("missing arguments", func(t *testing.T) { runGenerator(t, nil, 2, "usage: genversion") })
	t.Run("source failure", func(t *testing.T) {
		runGenerator(t, []string{"-source", source + ".missing", "-output", filepath.Join(t.TempDir(), "version.go")}, 1, "generate builder ai version: read source")
	})
	t.Run("output read failure", func(t *testing.T) {
		runGenerator(t, []string{"-source", source, "-output", t.TempDir()}, 1, "read output")
	})
	for _, tt := range []struct{ name, suffix, want string }{
		{"output directory failure", "nested/version.go", "create output dir"},
		{"output write failure", "version.go", "write output"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			if runtime.GOOS == "windows" || os.Geteuid() == 0 {
				t.Skip("requires Unix permission enforcement")
			}
			dir := t.TempDir()
			if err := os.Chmod(dir, 0o555); err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() { _ = os.Chmod(dir, 0o755) })
			runGenerator(t, []string{"-source", source, "-output", filepath.Join(dir, tt.suffix)}, 1, tt.want)
		})
	}
}

func runGenerator(t *testing.T, args []string, code int, want string) {
	t.Helper()
	encoded, err := json.Marshal(args)
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.CommandContext(t.Context(), os.Args[0], "-test.run=^TestGenerateVersion$")
	cmd.Env = append(os.Environ(), "SPX_GENVERSION_TEST_ARGS="+string(encoded))
	if f := flag.Lookup("test.gocoverdir"); f != nil && f.Value.String() != "" {
		dir := f.Value.String()
		cmd.Args = append(cmd.Args, "-test.gocoverdir="+dir)
		cmd.Env = append(cmd.Env, "GOCOVERDIR="+dir)
	}
	output, err := cmd.CombinedOutput()
	if cmd.ProcessState == nil || cmd.ProcessState.ExitCode() != code {
		t.Fatalf("generator exit=%v error=%v, want %d\n%s", cmd.ProcessState, err, code, output)
	}
	if !strings.Contains(string(output), want) {
		t.Fatalf("output=%q, want %q", output, want)
	}
}
