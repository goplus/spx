func TestModuleDependencyFromFile(t *testing.T) {
	const requirement = "module example.com/demo\nrequire " + modulePath + " v1.2.3\n"
	wantVersion := moduleDependency{Version: "v1.2.3"}
	wantReplacement := moduleDependency{Version: "v1.2.3", ReplacementPath: "example.com/ai", ReplacementVersion: "v1.4.0"}
	for _, tt := range []struct {
		name, content, wantError string
		want                     moduleDependency
		missing                  bool
	}{
		{name: "missing file", missing: true, wantError: "read source"},
		{name: "invalid module", content: "not a go.mod", wantError: "parse source"},
		{name: "missing requirement", content: "module example.com/demo\n", wantError: "not found"},
		{name: "matching requirement", content: requirement, want: wantVersion},
		{name: "remote replacement", content: requirement + "replace " + modulePath + " => example.com/ai v1.4.0\n", want: wantReplacement},
		{name: "versioned replacement", content: requirement + "replace " + modulePath + " v1.2.3 => example.com/ai v1.4.0\n", want: wantReplacement},
		{name: "other version replacement", content: requirement + "replace " + modulePath + " v1.2.2 => ../old-ai\n", want: wantVersion},
		{name: "unrelated replacement", content: requirement + "replace example.com/other => ../local\n", want: wantVersion},
		{name: "exact version overrides wildcard", content: requirement + "replace " + modulePath + " => ../local\nreplace " + modulePath + " v1.2.3 => example.com/ai v1.4.0\n", want: wantReplacement},
		{name: "exact version precedes wildcard", content: requirement + "replace " + modulePath + " v1.2.3 => example.com/ai v1.4.0\nreplace " + modulePath + " => ../local\n", want: wantReplacement},
		{name: "local replacement", content: requirement + "replace " + modulePath + " => ../local-ai\n", wantError: "replacement must use a remote module with a version"},
		{name: "invalid remote replacement", content: requirement + "replace " + modulePath + " => invalid-path v1.4.0\n", wantError: "invalid builder ai replacement"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			source := filepath.Join(t.TempDir(), "go.mod")
			if !tt.missing {
				if err := os.WriteFile(source, []byte(tt.content), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			dependency, err := moduleDependencyFromFile(source)
			if tt.wantError == "" {
				if err != nil || dependency != tt.want {
					t.Fatalf("dependency=%+v error=%v, want %+v", dependency, err, tt.want)
				}
			} else if err == nil || !strings.Contains(err.Error(), tt.wantError) || dependency != (moduleDependency{}) {
				t.Fatalf("dependency=%+v error=%v, want %q error", dependency, err, tt.wantError)
			}
		})
	}
}

func TestGenerateVersion(t *testing.T) {
	source := filepath.Join(t.TempDir(), "go.mod")
	if err := os.WriteFile(source, []byte("module example.com/demo\nrequire "+modulePath+" v1.2.3\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, tt := range []struct{ name, replacement, want string }{
		{"required version", "", "const ReplacementPath = \"\"\nconst ReplacementVersion = \"\"\n"},
		{"remote replacement", "replace " + modulePath + " => example.com/ai v1.4.0\n", "const ReplacementPath = \"example.com/ai\"\nconst ReplacementVersion = \"v1.4.0\"\n"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			source := filepath.Join(dir, "go.mod")
			content := "module example.com/demo\nrequire " + modulePath + " v1.2.3\n" + tt.replacement
			if err := os.WriteFile(source, []byte(content), 0o644); err != nil {
				t.Fatal(err)
			}
			output := filepath.Join(dir, "generated", "version_gen.go")
			args := []string{"-source", source, "-output", output}
			runGenerator(t, args, 0, "")
			data, err := os.ReadFile(output)
			want := "// Code generated by go generate; DO NOT EDIT.\n\npackage builderai\n\nconst Version = \"v1.2.3\"\n" + tt.want
			if err != nil || string(data) != want {
				t.Fatalf("generated dependency=%q error=%v, want %q", data, err, want)
			}
			stamp := time.Unix(1_600_000_000, 0)
			if err := os.Chtimes(output, stamp, stamp); err != nil {
				t.Fatal(err)
			}
			before, err := os.Stat(output)
			if err != nil {
				t.Fatal(err)
			}
			runGenerator(t, args, 0, "")
			after, err := os.Stat(output)
			if err != nil {
				t.Fatal(err)
			}
			if !os.SameFile(before, after) || !after.ModTime().Equal(before.ModTime()) {
				t.Fatal("identical generated file was rewritten")
			}
		})
	}
	t.Run("source failure", func(t *testing.T) {
		runGenerator(t, []string{"-source", source + ".missing", "-output", filepath.Join(t.TempDir(), "version.go")}, 1, "generate builder ai version: read source")
	})
	t.Run("output read failure", func(t *testing.T) {
		runGenerator(t, []string{"-source", source, "-output", t.TempDir()}, 1, "read output")
	})
}

func TestRunArguments(t *testing.T) {
	// Argument validation and help must not access the source file.
	source := filepath.Join(t.TempDir(), "missing.mod")
	output := filepath.Join(t.TempDir(), "version.go")
	for _, tt := range []struct {
		name string
		args []string
		code int
		want string
	}{
		{"short help", []string{"-h"}, 0, "usage: genversion"},
		{"help", []string{"-help"}, 0, "usage: genversion"},
		{"long help", []string{"--help"}, 0, "usage: genversion"},
		{"help after flags", []string{"-source", source, "-output", output, "-h"}, 0, "usage: genversion"},
		{"unknown flag", []string{"-unknown"}, 2, "flag provided but not defined"},
		{"source missing value", []string{"-source"}, 2, "flag needs an argument"},
		{"output missing value", []string{"-output"}, 2, "flag needs an argument"},
		{"missing arguments", nil, 2, "usage: genversion"},
		{"missing source", []string{"-output", output}, 2, "usage: genversion"},
		{"missing output", []string{"-source", source}, 2, "usage: genversion"},
		{"empty source", []string{"-source=", "-output", output}, 2, "usage: genversion"},
		{"empty output", []string{"-source", source, "-output="}, 2, "usage: genversion"},
		{"extra argument", []string{"-source", source, "-output", output, "extra"}, 2, "unexpected arguments"},
		{"argument after separator", []string{"-source", source, "-output", output, "--", "extra"}, 2, "unexpected arguments"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			stderr := runGenerator(t, tt.args, tt.code, tt.want)
			if strings.Count(stderr, "usage: genversion") != 1 {
				t.Fatalf("expected usage exactly once: %s", stderr)
			}
			if _, err := os.Stat(output); !os.IsNotExist(err) {
				t.Fatalf("invalid or help arguments generated output: %v", err)
			}
		})
	}
}

func TestGeneratePermissionErrors(t *testing.T) {
	if runtime.GOOS == "windows" || os.Geteuid() == 0 {
		t.Skip("requires Unix permission enforcement")
	}
	for _, operation := range []string{"read source", "read output", "create output dir", "write output"} {
		t.Run(operation, func(t *testing.T) {
			dir := t.TempDir()
			source := filepath.Join(dir, "go.mod")
			if err := os.WriteFile(source, []byte("module example.com/demo\nrequire "+modulePath+" v1.2.3\n"), 0o644); err != nil {
				t.Fatal(err)
			}
			output := filepath.Join(dir, "version.go")
			protected, mode := dir, os.FileMode(0o555)
			switch operation {
			case "read source":
				protected, mode = source, 0
			case "read output":
				if err := os.WriteFile(output, []byte("old content"), 0o644); err != nil {
					t.Fatal(err)
				}
				protected, mode = output, 0
			case "create output dir":
				output = filepath.Join(dir, "nested", "version.go")
			}
			if err := os.Chmod(protected, mode); err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() { _ = os.Chmod(protected, 0o755) })
			err := generate(source, output)
			if !errors.Is(err, os.ErrPermission) || !strings.Contains(err.Error(), operation) {
				t.Fatalf("generate error=%v, want %q permission error", err, operation)
			}
		})
	}
}

func runGenerator(t *testing.T, args []string, code int, want string) string {
	t.Helper()
	var stderr bytes.Buffer
	if got := run(args, &stderr); got != code {
		t.Fatalf("generator exit=%d, want %d\n%s", got, code, &stderr)
	}
	output := stderr.String()
	if !strings.Contains(output, want) || want == "" && output != "" {
		t.Fatalf("output=%q, want %q", output, want)
	}
	if code == 1 && strings.Count(output, "generate builder ai version:") != 1 {
		t.Fatalf("expected generation error exactly once: %s", output)
	}
	return output
}
